"""Build the portable trainer configuration from resolved launch settings."""

from __future__ import annotations

from pathlib import Path

from clean_simulation.internal_nn_runtime.cutcell_ml.config import DataConfig, RunConfig, TrainingConfig


def build_run_config(
    *,
    data_path: Path,
    model_type: str,
    batch_size: int,
    fusion_dim: int,
    residual_blocks: int,
    n_attention_heads: int | None,
    residual_scaling: str,
    transformer_ordered_sdf_branch: bool,
    weight_decay: float,
    optimizer_type: str,
    sgd_momentum: float,
    lbfgs_max_iter: int,
    lbfgs_history_size: int,
    lbfgs_line_search_fn: str | None,
    lbfgs_reset_history_per_batch: bool,
    epochs: int,
    initial_lr: float,
    scheduler_type: str,
    cosine_eta_min_factor: float,
    training_seed: int,
    split_seed: int,
    shuffle_seed: int,
    hard_example_drop_fraction: float,
    excluded_geometry_prefixes: tuple[str, ...],
    max_wall_seconds: float | None,
    distributed: bool,
    num_workers: int,
    prefetch_factor: int,
    use_amp: bool,
    refined_subcells: int,
) -> RunConfig:
    return RunConfig(
        data=DataConfig(
            h5_path=data_path,
            depth=2,
            integration_order=2,
            poly_order=1,
            poisson_ratio=0.3,
            min_samples=0,
            max_load_samples=None,
            refined_subcells=refined_subcells,
            value_resolution=1,
        ),
        training=TrainingConfig(
            model_type=model_type,
            batch_size=batch_size,
            fusion_dim=fusion_dim,
            n_residual_blocks=residual_blocks,
            n_attention_heads=n_attention_heads,
            include_nu=False,
            use_class_conditioning=False,
            include_class_inputs=False,
            trunk_type="resnet",
            residual_scaling=residual_scaling,
            transformer_ordered_sdf_branch=transformer_ordered_sdf_branch,
            spd_mode="cholesky",
            use_reduced_null_space=True,
            matrix_size=24,
            dropout_p=0.0,
            weight_decay=weight_decay,
            optimizer_type=optimizer_type,
            sgd_momentum=sgd_momentum,
            lbfgs_max_iter=lbfgs_max_iter,
            lbfgs_history_size=lbfgs_history_size,
            lbfgs_line_search_fn=lbfgs_line_search_fn,
            lbfgs_reset_history_per_batch=lbfgs_reset_history_per_batch,
            grad_clip_norm=1.0,
            epochs=epochs,
            lr=initial_lr,
            scheduler_type=scheduler_type,
            cosine_eta_min_factor=cosine_eta_min_factor,
            train_split=0.9,
            seed=training_seed,
            split_seed=split_seed,
            shuffle_seed=shuffle_seed,
            hard_example_drop_fraction=hard_example_drop_fraction,
            excluded_geometry_prefixes=excluded_geometry_prefixes,
            standardize_inputs=True,
            use_decoupled_loss=False,
            physical_loss_weight=1.0,
            classifier_weight=0.0,
            fourier_loss_weight=0.0,
            energy_loss_weight=0.0,
            nullspace_loss_weight=0.0,
            soft_mode_loss_weight=0.0,
            warmup_phys_only_epochs=0,
            aux_ramp_epochs=0,
            early_stopping_patience=epochs + 1,
            early_stopping_min_delta=0.0,
            max_wall_seconds=max_wall_seconds,
            use_distributed=distributed,
            num_workers=num_workers,
            pin_memory=True,
            persistent_workers=True,
            prefetch_factor=prefetch_factor,
            use_amp=use_amp,
        ),
    )